/**
 * KYNEX static-string layer — the UI-chrome half of the Global Language
 * Engine.
 *
 * `languages.ts` owns WHICH language is active (BCP-47 code, <html lang/dir>,
 * persistence). This module owns the fixed interface strings: shell chrome,
 * navigation, and the section labels of the core modules. Dynamic content
 * (AI answers, material titles, tutor copy) is handled by the AI language
 * directives in aiEngine.ts instead — those flow through the allowlisted
 * LANGUAGE_DIRECTIVES map, never through this file.
 *
 * Design rules, same discipline as the rest of the pref system:
 *  - English is the source of truth. Its keys define `DictKey`, so any
 *    language dictionary missing a key (or carrying a stray one) is a
 *    compile-time error, and the parity test in i18n.test.ts can't drift.
 *  - `translate` is total: an unknown language or missing entry falls back to
 *    English rather than rendering `undefined` into the DOM.
 *  - Interpolation is token-based ({n}, {m}) — never string concatenation —
 *    so translations may reorder words freely. Unknown tokens survive
 *    verbatim instead of collapsing to "undefined".
 *  - Brand nouns (KYNEX, Vault, Twin, KYNEX Brain, KYNEX Map, GPA Lab) stay
 *    untranslated in every language: they are product names, not prose.
 */

